export const getAboutText = (key, locale = 'zh-CN') => {
  // 支持多种中文 locale 格式
  const isChinese = locale === 'zh-CN' || locale === 'zh' || locale.startsWith('zh')
  const texts = isChinese ? aboutText['zh-CN'] : aboutText['en-US']
  return key.split('.').reduce((obj, k) => obj?.[k], texts) || key
} 